def validate_multi_blank(spec):
    """多空选词填空程序校验"""
    errors = []
    # 4个选项
    if len(spec["options"]) != 4:
        errors.append("选项数不为4")
    # 每个选项2个词（空格分隔）
    for k, v in spec["options"].items():
        words = v.split()
        if len(words) != 2:
            errors.append(f"选项{k}不是2词组合: {v}")
    # 答案唯一
    if spec["answer"] not in spec["options"]:
        errors.append("答案不在选项中")
    # 选项互异
    if len(set(spec["options"].values())) != 4:
        errors.append("选项存在重复")
    # 干扰项标注完整
    for k in ["A", "B", "C", "D"]:
        if k != spec["answer"] and k not in spec["distractors"]:
            errors.append(f"干扰项{k}缺少标注")
    return errors


def validate_sentence_order(spec):
    """语句排序程序校验"""
    errors = []
    # 5个句子
    if len(spec["sentences"]) != 5:
        errors.append(f"句子数不为5: {len(spec['sentences'])}")
    # 正确顺序包含所有5个句子编号
    correct = spec["correct_order"]
    if len(correct) != 5 or set(correct) != set("①②③④⑤"):
        errors.append(f"正确顺序不完整: {correct}")
    # 4个选项，每个是5个编号的排列
    if len(spec["options"]) != 4:
        errors.append("选项数不为4")
    for k, v in spec["options"].items():
        if len(v) != 5 or set(v) != set("①②③④⑤"):
            errors.append(f"选项{k}格式错误: {v}")
    # 答案对应正确顺序
    if spec["options"][spec["answer"]] != correct:
        errors.append(f"答案{spec['answer']}对应的顺序不是正确顺序")
    # 干扰项标注
    for k in ["A", "B", "C", "D"]:
        if k != spec["answer"] and k not in spec["distractors"]:
            errors.append(f"干扰项{k}缺少标注")
    return errors


