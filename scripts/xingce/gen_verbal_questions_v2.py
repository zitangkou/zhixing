def _load_llm_config():
    """从 server/.env 读取 LLM 配置，不打印 key"""
    env_path = REPO_ROOT / "server" / ".env"
    config = {"enabled": False, "api_key": None, "base_url": None, "model": None, "timeout": 60}
    if not env_path.exists():
        return config
    with open(env_path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, _, val = line.partition("=")
            key = key.strip()
            val = val.strip().strip('"').strip("'")
            if key == "LLM_ENABLED":
                config["enabled"] = val.lower() in ("true", "1", "yes")
            elif key == "LLM_API_KEY":
                config["api_key"] = val
            elif key == "LLM_BASE_URL":
                config["base_url"] = val
            elif key == "LLM_MODEL":
                config["model"] = val
            elif key == "LLM_TIMEOUT_SECONDS":
                try:
                    config["timeout"] = int(val)
                except ValueError:
                    pass
    return config


def llm_blind_answer(question_text, options_text, config):
    """
    LLM 独立盲审：只给题干+选项，不给答案，让 LLM 选择最佳选项。
    返回 (answer_letter, raw_response) 或 (None, error_msg)。
    """
    if not config["enabled"] or not config["api_key"]:
        return None, "LLM not enabled or no API key"

    import urllib.request
    import urllib.error

    system_prompt = (
        "你是一位公务员考试行测言语理解模块的资深教研员。"
        "请仔细阅读题目和选项，选择唯一正确的答案。"
        "只输出 JSON 格式：{\"answer\": \"A\"或\"B\"或\"C\"或\"D\", \"reason\": \"简短理由\"}"
    )
    user_prompt = f"题目：\n{question_text}\n\n选项：\n{options_text}\n\n请选择正确答案。"

    url = f"{config['base_url'].rstrip('/')}/chat/completions"
    payload = json.dumps({
        "model": config["model"],
        "messages": [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_prompt},
        ],
        "response_format": {"type": "json_object"},
        "temperature": 0.3,
    }).encode("utf-8")

    req = urllib.request.Request(
        url,
        data=payload,
        headers={
            "Authorization": f"Bearer {config['api_key']}",
            "Content-Type": "application/json",
        },
        method="POST",
    )

    try:
        with urllib.request.urlopen(req, timeout=config["timeout"]) as resp:
            data = json.loads(resp.read().decode("utf-8"))
        content = data["choices"][0]["message"]["content"]
        result = json.loads(content)
        answer = result.get("answer", "").strip().upper()
        if answer in ("A", "B", "C", "D"):
            return answer, result.get("reason", "")
        return None, f"Invalid answer: {answer}"
    except urllib.error.HTTPError as e:
        return None, f"HTTP {e.code}: {e.read().decode('utf-8')[:200]}"
    except Exception as e:
        return None, f"Error: {str(e)[:200]}"


