def main():
    parser = argparse.ArgumentParser(description="Q5言语理解引擎v2")
    parser.add_argument("--no-llm", action="store_true", help="跳过LLM盲审")
    parser.add_argument("--dry-run", action="store_true", help="dry-run模式（LLM模拟正确）")
    args = parser.parse_args()

    random.seed(SEED)

    print("=" * 60)
    print("Q5 言语理解引擎 v2 — 多空选词/语句排序/标题选择")
    print("=" * 60)

    # ── 加载v1题目 ──
    v1_questions = []
    if V1_QUESTIONS_PATH.exists():
        with open(V1_QUESTIONS_PATH, encoding="utf-8") as f:
            v1_data = json.load(f)
        v1_questions = v1_data.get("questions", [])
        print(f"\n[v1] 加载原有题目: {len(v1_questions)}题")
    else:
        print(f"\n[v1] 未找到{v1_questions}，将只生成新增题目")

    # ── 生成多空选词填空 ──
    print(f"\n[1/3] 生成 {len(MULTI_BLANK_SPECS)} 道多空选词填空题...")
    multi_blank_questions = []
    failed = []
    for spec in MULTI_BLANK_SPECS:
        errors = validate_multi_blank(spec)
        if errors:
            print(f"  ❌ {spec['question_id']} 校验失败: {errors}")
            failed.append(spec["question_id"])
            continue
        q = build_multi_blank_question(spec)
        multi_blank_questions.append(q)
        status = "✅" if q["dual_solve"]["passed"] else "⚠️"
        print(f"  {status} {spec['question_id']} (难度{spec['difficulty']}) 答案={spec['answer']} 盲审={q['dual_solve']['agreement']}")

    # ── 生成语句排序 ──
    print(f"\n[2/3] 生成 {len(SENTENCE_ORDER_SPECS)} 道语句排序题...")
    order_questions = []
    for spec in SENTENCE_ORDER_SPECS:
        errors = validate_sentence_order(spec)
        if errors:
            print(f"  ❌ {spec['question_id']} 校验失败: {errors}")
            failed.append(spec["question_id"])
            continue
        q = build_sentence_order_question(spec)
        order_questions.append(q)
        status = "✅" if q["dual_solve"]["passed"] else "⚠️"
        print(f"  {status} {spec['question_id']} (难度{spec['difficulty']}) 答案={spec['answer']} 盲审={q['dual_solve']['agreement']}")

    # ── 生成标题选择 ──
    print(f"\n[3/3] 生成 {len(TITLE_SELECTION_SPECS)} 道标题选择题...")
    title_questions = []
    for spec in TITLE_SELECTION_SPECS:
        errors = validate_title_selection(spec)
        if errors:
            print(f"  ❌ {spec['question_id']} 校验失败: {errors}")
            failed.append(spec["question_id"])
            continue
        q = build_title_question(spec)
        title_questions.append(q)
        status = "✅" if q["dual_solve"]["passed"] else "⚠️"
        print(f"  {status} {spec['question_id']} (难度{spec['difficulty']}) 答案={spec['answer']} 盲审={q['dual_solve']['agreement']}")

    # ── 合并所有题目 ──
    new_questions = multi_blank_questions + order_questions + title_questions
    all_questions = v1_questions + new_questions

    print(f"\n{'=' * 60}")
    print(f"生成汇总: 新增{len(new_questions)}题 + 原有{len(v1_questions)}题 = 共{len(all_questions)}题")
    print(f"程序校验失败: {len(failed)}题")
    rule_passed = sum(1 for q in new_questions if q["dual_solve"]["passed"])
    print(f"规则盲审通过: {rule_passed}/{len(new_questions)}")

    # ── LLM盲审 ──
    llm_results = []
    if not args.no_llm:
        config = _load_llm_config()
        if config["enabled"] and config["api_key"]:
            llm_results = run_llm_blind_review(all_questions, config, dry_run=args.dry_run)
        else:
            print("\n  ⚠️ LLM未启用，跳过LLM盲审（在server/.env设置LLM_ENABLED=true和LLM_API_KEY）")

    # ── 写产出文件 ──
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    output_data = {
        "template_version": TEMPLATE_VERSION,
        "seed": SEED,
        "generated_at": datetime.now().isoformat(),
        "total_questions": len(all_questions),
        "v1_questions": len(v1_questions),
        "v2_new_questions": len(new_questions),
        "questions": all_questions,
    }

    with open(V2_QUESTIONS_PATH, "w", encoding="utf-8") as f:
        json.dump(output_data, f, ensure_ascii=False, indent=2)
    print(f"\n✅ 题目: {V2_QUESTIONS_PATH} ({V2_QUESTIONS_PATH.stat().st_size} bytes)")

    # ── 写报告 ──
    report = generate_report(all_questions, v1_questions, failed, llm_results)
    with open(V2_REPORT_PATH, "w", encoding="utf-8") as f:
        f.write(report)
    print(f"✅ 报告: {V2_REPORT_PATH} ({V2_REPORT_PATH.stat().st_size} bytes)")

    print(f"\n{'=' * 60}")
    print(f"完成: 共{len(all_questions)}题（新增{len(new_questions)}题），{len(failed)}题校验失败")
    if llm_results:
        llm_pass = sum(1 for r in llm_results if r["match"])
        print(f"LLM盲审: {llm_pass}/{len(llm_results)} 一致")
    print("=" * 60)


if __name__ == "__main__":
    main()
