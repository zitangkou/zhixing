def run_llm_blind_review(all_questions, config, dry_run=False):
    """对所有题目执行LLM独立盲审"""
    if not config["enabled"] or not config["api_key"]:
        print("  ⚠️ LLM未启用或无API key，跳过LLM盲审")
        return []

    results = []
    total = len(all_questions)
    print(f"\n[LLM盲审] 对 {total} 道题执行LLM独立作答（model={config['model']}）...")

    auth_failed = False
    for i, q in enumerate(all_questions):
        if auth_failed:
            # 认证失败后，剩余题目标记为unavailable
            results.append({
                "question_id": q["question_id"],
                "subtype": q["subtype"],
                "correct_answer": q["answer"],
                "llm_answer": None,
                "llm_reason": "skipped: auth_failed",
                "match": False,
                "llm_enabled": config["enabled"],
                "model": config["model"],
                "unavailable": True,
            })
            continue

        # 构建题干文本
        if q["subtype"] == "语句排序":
            question_text = q["stem"] + "\n" + "\n".join(q.get("sentences", []))
        else:
            question_text = q["passage"] + "\n" + q["stem"]

        options_text = "\n".join(f"{k}. {v}" for k, v in q["options"].items())

        if dry_run:
            llm_answer = q["answer"]
            reason = "dry-run"
        else:
            llm_answer, reason = llm_blind_answer(question_text, options_text, config)

        # 检测认证失败
        if llm_answer is None and isinstance(reason, str) and "401" in reason:
            auth_failed = True
            print(f"  ❌ LLM认证失败（API key无效），跳过剩余题目")
            results.append({
                "question_id": q["question_id"],
                "subtype": q["subtype"],
                "correct_answer": q["answer"],
                "llm_answer": None,
                "llm_reason": reason[:100],
                "match": False,
                "llm_enabled": config["enabled"],
                "model": config["model"],
                "unavailable": True,
            })
            continue

        match = (llm_answer == q["answer"])
        results.append({
            "question_id": q["question_id"],
            "subtype": q["subtype"],
            "correct_answer": q["answer"],
            "llm_answer": llm_answer,
            "llm_reason": reason if isinstance(reason, str) else str(reason)[:100],
            "match": match,
            "llm_enabled": config["enabled"],
            "model": config["model"],
        })

        # 更新题目review_status（兼容v1字符串格式和v2字典格式）
        if isinstance(q.get("review_status"), dict):
            q["review_status"]["llm_blind_review"] = "pass" if match else "fail"
            if not match:
                q["review_status"]["llm_blind_review_note"] = f"LLM选了{llm_answer}，正确答案为{q['answer']}"
        else:
            q["review_status"] = {
                "program_check": "pass",
                "rule_blind_review": "pass",
                "llm_blind_review": "pass" if match else "fail",
            }

        status = "✅" if match else "❌"
        print(f"  [{i+1}/{total}] {status} {q['question_id']} 正确={q['answer']} LLM={llm_answer}")

    if auth_failed:
        print(f"\n  LLM盲审状态: 不可用（API key认证失败，需在server/.env更新有效的LLM_API_KEY）")
    else:
        passed = sum(1 for r in results if r["match"])
        print(f"\n  LLM盲审汇总: {passed}/{total} 一致 ({passed*100//total}%)")
    return results


