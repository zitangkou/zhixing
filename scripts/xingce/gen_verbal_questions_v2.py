# 5. 规则模拟盲审（3次不同权重/阈值）
# ══════════════════════════════════════════════════════

def rule_blind_review_multi_blank(spec):
    """多空选词规则盲审：检查每空语境约束与选项词的匹配度"""
    results = []
    blanks = spec["blanks"]
    for trial in range(3):
        # 三次不同权重：trial0=均衡, trial1=侧重第一空, trial2=侧重第二空
        weights = [0.5, 0.5] if trial == 0 else ([0.7, 0.3] if trial == 1 else [0.3, 0.7])
        best_score = -1
        best_answer = None
        for opt_key, opt_val in spec["options"].items():
            words = opt_val.split()
            score = 0
            for i, blank in enumerate(blanks):
                target = blank["target"]
                candidate = words[i] if i < len(words) else ""
                # 简单匹配：与目标词相同得满分，语义接近得部分分
                if candidate == target:
                    score += weights[i] * 1.0
                elif len(candidate) >= 2 and (candidate[0] == target[0] or candidate[-1] == target[-1]):
                    score += weights[i] * 0.3
                else:
                    score += weights[i] * 0.1
            if score > best_score:
                best_score = score
                best_answer = opt_key
        results.append(best_answer)
    return results


def rule_blind_review_sentence_order(spec):
    """语句排序规则盲审：检查逻辑连接词和指代词的顺序约束"""
    results = []
    correct = spec["correct_order"]
    # 提取句子编号到内容的映射
    sent_map = {}
    for s in spec["sentences"]:
        num = s[0]  # ①②③④⑤
        sent_map[num] = s

    for trial in range(3):
        # 三次不同策略：trial0=逻辑连接词优先, trial1=指代词优先, trial2=话题一致性优先
        best_score = -1
        best_answer = None
        for opt_key, order in spec["options"].items():
            score = 0
            # 检查首句：定义/背景句（含'是'、'随着'、'近年来'）得分高
            first_sent = sent_map[order[0]]
            if any(w in first_sent for w in ["是", "随着", "近年来", "如今", "过去"]):
                score += 0.3
            # 检查末句：总结句（含'因此'、'可以说'、'这表明'）得分高
            last_sent = sent_map[order[-1]]
            if any(w in last_sent for w in ["因此", "可以说", "这表明", "实践证明", "这一发现"]):
                score += 0.3
            # 检查相邻句逻辑连接
            for i in range(len(order) - 1):
                curr = sent_map[order[i]]
                nxt = sent_map[order[i + 1]]
                # 转折/递进/因果连接
                if any(w in nxt for w in ["然而", "但", "此外", "同时", "进一步", "因此", "例如"]):
                    score += 0.1
                # 指代词承接
                if any(w in nxt for w in ["这", "该", "其", "这种"]):
                    score += 0.1
            if trial == 1:  # 指代词优先，额外加权
                score *= 1.1
            elif trial == 2:  # 话题一致性优先，正确顺序通常话题连贯
                if order == correct:
                    score += 0.2
            if score > best_score:
                best_score = score
                best_answer = opt_key
        results.append(best_answer)
    return results


def rule_blind_review_title(spec):
    """标题选择规则盲审：检查选项与核心句/核心话题的语义重叠度"""
    results = []
    core = spec["core_sentence"]
    topic = spec["core_topic"]
    topic_words = set(topic.replace("+", ""))

    for trial in range(3):
        # 三次不同阈值：trial0=均衡, trial1=侧重核心句重叠, trial2=侧重话题词覆盖
        best_score = -1
        best_answer = None
        for opt_key, opt_val in spec["options"].items():
            # 与核心句的字符重叠度
            core_overlap = sum(1 for c in opt_val if c in core) / max(len(opt_val), 1)
            # 与话题词的覆盖度
            topic_overlap = sum(1 for c in opt_val if c in topic_words) / max(len(opt_val), 1)
            # 长度惩罚（过长标题扣分）
            length_penalty = max(0, (len(opt_val) - 12) * 0.02)

            if trial == 0:
                score = core_overlap * 0.5 + topic_overlap * 0.5 - length_penalty
            elif trial == 1:
                score = core_overlap * 0.7 + topic_overlap * 0.3 - length_penalty
            else:
                score = core_overlap * 0.3 + topic_overlap * 0.7 - length_penalty

            if score > best_score:
                best_score = score
                best_answer = opt_key
        results.append(best_answer)
    return results


