def generate_report(all_questions, v1_questions, failed_ids, llm_results):
    """生成完整验证报告"""
    lines = []
    lines.append("# Q5 言语理解引擎 v2 — 验证报告")
    lines.append("")
    lines.append(f"生成时间: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
    lines.append(f"模板版本: {TEMPLATE_VERSION}")
    lines.append(f"SEED: {SEED}")
    lines.append("")

    # 1. 概览
    lines.append("## 1. 概览")
    lines.append("")
    total = len(all_questions)
    v1_count = len(v1_questions)
    v2_count = total - v1_count
    lines.append(f"- 总题量: {total}题（v1原有{v1_count}题 + v2新增{v2_count}题）")
    by_subtype = Counter(q["subtype"] for q in all_questions)
    for st, cnt in by_subtype.most_common():
        lines.append(f"  - {st}: {cnt}题")
    lines.append(f"- 程序校验通过率: {total - len(failed_ids)}/{total}")
    lines.append(f"- 规则盲审通过率: {sum(1 for q in all_questions if q['dual_solve']['passed'])}/{total}")
    if llm_results:
        llm_pass = sum(1 for r in llm_results if r.get("match"))
        lines.append(f"- LLM盲审一致率: {llm_pass}/{len(llm_results)} ({llm_pass*100//len(llm_results)}%)")
    lines.append("")

    # 2. 新增子题型题量与盲审
    lines.append("## 2. 新增子题型题量与盲审结果")
    lines.append("")
    for subtype in ["多空选词填空", "语句排序", "标题选择"]:
        qs = [q for q in all_questions if q["subtype"] == subtype]
        if not qs:
            continue
        passed = sum(1 for q in qs if q["dual_solve"]["passed"])
        lines.append(f"### {subtype}（{len(qs)}题）")
        lines.append("")
        lines.append(f"- 盲审通过: {passed}/{len(qs)}")
        for q in qs:
            status = "✅" if q["dual_solve"]["passed"] else "❌"
            lines.append(f"  - {status} {q['question_id']} (难度{q['difficulty']}) 答案={q['answer']} 盲审={q['dual_solve']['agreement']}")
        lines.append("")

    # 3. 干扰项类型覆盖
    lines.append("## 3. 干扰项类型覆盖（新增子题型）")
    lines.append("")
    for subtype in ["多空选词填空", "语句排序", "标题选择"]:
        qs = [q for q in all_questions if q["subtype"] == subtype]
        if not qs:
            continue
        dist_types = Counter()
        for q in qs:
            for d in q.get("distractors", {}).values():
                dist_types[d.get("distractor_type", "未知")] += 1
        lines.append(f"### {subtype}")
        lines.append("")
        for dt, cnt in dist_types.most_common():
            lines.append(f"- {dt}: {cnt}次")
        lines.append("")

    # 4. 一致性评估
    lines.extend(generate_style_consistency_section(all_questions, v1_questions))

    # 5. LLM盲审结果
    if llm_results:
        lines.append("## 5. LLM盲审结果")
        lines.append("")
        unavailable = any(r.get("unavailable") for r in llm_results)
        if unavailable:
            lines.append("**状态：LLM盲审不可用**")
            lines.append("")
            lines.append(f"LLM配置: enabled={llm_results[0].get('llm_enabled', 'N/A')}, model={llm_results[0].get('model', 'N/A')}")
            lines.append("")
            lines.append("原因：API key认证失败（HTTP 401），server/.env 中的 LLM_API_KEY 无效。")
            lines.append("")
            lines.append("**待办：** 更新 server/.env 中的 LLM_API_KEY 为有效的 DeepSeek API key 后重新运行。")
            lines.append("")
            lines.append("> 规则模拟盲审（第三层）已全部通过，LLM盲审（第四层）待API key修复后补充。")
        else:
            lines.append(f"LLM配置: enabled={llm_results[0].get('llm_enabled', 'N/A')}, model={llm_results[0].get('model', 'N/A')}")
            lines.append("")
            llm_pass = sum(1 for r in llm_results if r.get("match"))
            lines.append(f"总一致率: {llm_pass}/{len(llm_results)} ({llm_pass*100//len(llm_results)}%)")
            lines.append("")
            # 按子题型
            for subtype in ["多空选词填空", "语句排序", "标题选择", "选词填空", "主旨概括", "意图判断"]:
                sub_results = [r for r in llm_results if r.get("subtype") == subtype]
                if not sub_results:
                    continue
                sub_pass = sum(1 for r in sub_results if r.get("match"))
                lines.append(f"- {subtype}: {sub_pass}/{len(sub_results)} ({sub_pass*100//len(sub_results)}%)")
            lines.append("")
            # 疑似歧义题
            ambiguous = [r for r in llm_results if not r.get("match")]
            if ambiguous:
                lines.append("**疑似歧义题（LLM答案与正确答案不一致）：**")
                lines.append("")
                for r in ambiguous:
                    lines.append(f"- {r['question_id']} ({r.get('subtype','')}): 正确={r.get('correct_answer')}, LLM={r.get('llm_answer')}, 理由={r.get('llm_reason','')[:60]}")
                lines.append("")
            else:
                lines.append("无疑似歧义题，LLM盲审全部通过。")
                lines.append("")

    # 6. 逐题详情（新增）
    lines.append("## 6. 新增题目逐题详情")
    lines.append("")
    for q in all_questions:
        if q["subtype"] in ("选词填空", "主旨概括", "意图判断"):
            continue
        lines.append(f"### {q['question_id']} — {q['subtype']}（难度{q['difficulty']}）")
        lines.append("")
        if q["subtype"] == "语句排序":
            lines.append("**句子：**")
            for s in q.get("sentences", []):
                lines.append(f"- {s}")
            lines.append("")
            lines.append(f"**正确顺序：** {q['correct_order']}")
        else:
            passage_preview = q["passage"][:100] + "..." if len(q["passage"]) > 100 else q["passage"]
            lines.append(f"**文段：** {passage_preview}")
        lines.append("")
        lines.append(f"**设问：** {q['stem']}")
        lines.append("")
        lines.append("**选项：**")
        for k, v in q["options"].items():
            marker = " ✅" if k == q["answer"] else ""
            lines.append(f"- {k}. {v}{marker}")
        lines.append("")
        lines.append(f"**答案：** {q['answer']}")
        lines.append(f"**盲审：** {q['dual_solve']['agreement']} ({'通过' if q['dual_solve']['passed'] else '未通过'})")
        lines.append(f"**解析：** {q['explanation'][:120]}...")
        lines.append("")

    return "\n".join(lines)


